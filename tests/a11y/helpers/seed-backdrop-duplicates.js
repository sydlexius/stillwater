// seed-backdrop-duplicates.js - fixture for the perceptual-duplicate a11y
// spec (#2716).
//
// WHY THIS EXISTS
//
// `make test-a11y` boots the server against a BRAND NEW EMPTY DATABASE and an
// EMPTY library directory (SW_DB_PATH / SW_EMPTY_LIB in the Makefile target).
// /reports/backdrop-duplicates therefore has no artists, no duplicates, and
// renders its pending or empty state: the perceptual notice, the stat tile,
// and the perceptual-only row badge cannot exist there at all.
//
// The spec's assertions are not softened to tolerate that. A conditional skip
// would report green forever while verifying nothing, which is worse than no
// spec: it is a guard wired to look like it is working. The gap is the absent
// DATA, so the fix is a fixture -- the same conclusion seed-blast-radius.js
// reached for the same harness property.
//
// Seeding a long-lived local database instead would go green on one machine
// and still fail in CI. This seeder runs inside the harness, against whatever
// server the run just started.
//
// WHAT THE REPORT ACTUALLY NEEDS
//
// The report counts two DISJOINT kinds of within-artist fanart redundancy, and
// the spec needs both present at once or it cannot tell them apart:
//
//   - EXACT: byte-identical files. Collapsible, and what the remediate button
//     acts on.
//   - PERCEPTUAL-ONLY: visually near-identical but byte-DIFFERENT, so the
//     exact tier cannot see them. These are what survive every run, and an
//     artist holding only these is the "false-clean row" the badge exists to
//     mark.
//
// So the fixture builds one artist of each, plus a clean artist that must NOT
// appear in the report (its absence is what proves the affected-gate is not
// simply counting everything).
//
// Perceptual-but-not-exact pairs are made by encoding ONE gradient at two JPEG
// qualities. Same picture, different bytes. That is the same construction the
// Go tests use (createGradientJPEGQuality), and it is generated by a tiny Go
// program rather than hand-rolled in Node: a hand-written JPEG encoder here
// would be a second, unvalidated implementation of the thing under test.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';

const BASE_URL = process.env.SW_TEST_URL
  || `http://127.0.0.1:${process.env.SW_PORT || '1973'}`;

const FIXTURE_LIBRARY_NAME = 'a11y backdrop-duplicates fixture';

// Artist names deliberately avoid containing the badge's rendered text
// ("Perceptual Only"). An earlier version of the spec asserted that string and
// passed against an artist NAMED "Perceptual Only Artist" -- the assertion
// matched the row's own name, so deleting the badge entirely still passed.
// The spec now targets a marker attribute, and these names keep it impossible
// for that class of collision to come back.
const PERCEPTUAL_ARTIST = 'Near Match Artist';
const EXACT_ARTIST = 'Byte Identical Artist';
const CLEAN_ARTIST = 'Single Fanart Artist';

// A Go program, written to the fixture dir and run with `go run`, because the
// repo's own JPEG fixtures are produced this way and the encoder must match
// what the duplicate detector was built against.
const GEN_SOURCE = `package main

import (
	"fmt"
	"image"
	"image/color"
	"image/jpeg"
	"os"
	"path/filepath"
)

// gradient mirrors createGradientJPEGQuality in internal/rule's tests: the
// variant shifts the hue ramp (a different variant is a visually DIFFERENT
// picture), the quality changes only the encoding (same picture, different
// bytes).
func gradient(path string, variant, quality int) error {
	const w, h = 400, 300
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			v := uint8((x*255/w + variant*37) % 256)
			img.Set(x, y, color.RGBA{R: v, G: 255 - v, B: 128, A: 255})
		}
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return jpeg.Encode(f, img, &jpeg.Options{Quality: quality})
}

func main() {
	root := os.Args[1]
	perceptual, exact, clean := os.Args[2], os.Args[3], os.Args[4]

	// Perceptual-only: one picture at five qualities. No two files are
	// byte-identical, so the exact tier finds nothing here and the artist is
	// affected on perceptual redundancy alone.
	dir := filepath.Join(root, perceptual)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	for i, q := range []int{95, 88, 80, 72, 64} {
		name := "fanart.jpg"
		if i > 0 {
			name = fmt.Sprintf("fanart%d.jpg", i+1)
		}
		if err := gradient(filepath.Join(dir, name), 30, q); err != nil {
			panic(err)
		}
	}

	// Exact: two byte-identical copies plus one genuinely different image.
	dir = filepath.Join(root, exact)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	if err := gradient(filepath.Join(dir, "fanart.jpg"), 7, 90); err != nil {
		panic(err)
	}
	src, err := os.ReadFile(filepath.Join(dir, "fanart.jpg"))
	if err != nil {
		panic(err)
	}
	for _, n := range []string{"fanart2.jpg", "fanart3.jpg"} {
		if err := os.WriteFile(filepath.Join(dir, n), src, 0o644); err != nil {
			panic(err)
		}
	}
	if err := gradient(filepath.Join(dir, "fanart4.jpg"), 55, 90); err != nil {
		panic(err)
	}

	// Clean: a single fanart cannot be redundant with anything, so this artist
	// must never appear in the report.
	dir = filepath.Join(root, clean)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	if err := gradient(filepath.Join(dir, "fanart.jpg"), 99, 90); err != nil {
		panic(err)
	}
}
`;

async function apiFetch(request, method, url, body) {
  const state = await request.storageState();
  const csrf = (state.cookies.find(c => c.name === 'csrf_token') || {}).value || '';
  const opts = {
    headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf },
  };
  if (body !== undefined) opts.data = JSON.stringify(body);
  return request.fetch(`${BASE_URL}${url}`, { method, ...opts });
}

async function ensureLibrary(request, dir) {
  const resp = await apiFetch(request, 'POST', '/api/v1/libraries', {
    name: FIXTURE_LIBRARY_NAME, path: dir, type: 'regular',
  });
  if (resp.ok()) return (await resp.json()).id;

  // 409 means a previous run created it. Reuse only when it still points where
  // this run expects: a stale row aimed at a deleted temp dir would scan
  // nothing and seed an empty fixture, which is exactly the failure this
  // helper exists to prevent.
  if (resp.status() === 409) {
    const list = await request.fetch(`${BASE_URL}/api/v1/libraries`);
    if (list.ok()) {
      const body = await list.json();
      const libs = Array.isArray(body) ? body : (body.libraries || []);
      const existing = libs.find(l => l.name === FIXTURE_LIBRARY_NAME);
      if (existing && existing.path === dir) return existing.id;
      if (existing) {
        throw new Error(
          `seed: fixture library exists but points at ${existing.path}, not ${dir}. `
          + 'Delete it (or use a fresh database) before re-seeding.',
        );
      }
    }
  }
  throw new Error(`seed: creating fixture library failed: ${resp.status()} ${await resp.text()}`);
}

async function runScan(request) {
  const resp = await apiFetch(request, 'POST', '/api/v1/scanner/run');
  if (!resp.ok()) {
    throw new Error(`seed: scanner run failed: ${resp.status()} ${await resp.text()}`);
  }
  const deadline = Date.now() + 60_000;
  while (Date.now() < deadline) {
    const st = await request.fetch(`${BASE_URL}/api/v1/scanner/status`);
    if (st.ok()) {
      const body = await st.json();
      if (body.status === 'completed' || body.status === 'idle') return;
    }
    await new Promise(r => setTimeout(r, 500));
  }
  throw new Error('seed: scan did not complete within 60s');
}

// The duplicate report is served from a CACHE populated by a background scan,
// not computed on render. The first GET finds a cold cache, renders the
// pending notice, and TRIGGERS that scan -- so the page must be polled until
// the real report lands. Returning early here would hand the spec the pending
// state and fail every assertion for a reason that has nothing to do with the
// code under test.
async function waitForReport(request) {
  const deadline = Date.now() + 90_000;
  let last = '';
  while (Date.now() < deadline) {
    const resp = await request.fetch(`${BASE_URL}/reports/backdrop-duplicates`);
    if (resp.ok()) {
      last = await resp.text();
      if (last.includes('id="backdrop-duplicates-table"')) return;
    }
    await new Promise(r => setTimeout(r, 2_000));
  }
  const pending = last.includes('backdrop-duplicates-unavailable-notice');
  throw new Error(
    `seed: the duplicate report did not populate within 90s (still ${pending ? 'pending' : 'unrecognised'}). `
    + 'The spec cannot verify a surface that never rendered.',
  );
}

/**
 * seedBackdropDuplicates builds a library holding one perceptual-only artist,
 * one exact-duplicate artist, and one clean artist, then waits for the
 * duplicate report to reflect them.
 *
 * Safe to re-run: the library row is reused when it already points at this
 * run's directory.
 */
export async function seedBackdropDuplicates(request) {
  // Scoped to the port so two servers on one machine cannot share a fixture
  // directory and scan each other's artists. Deterministic rather than a
  // random temp dir, so the 409-reuse branch above is actually reachable.
  const port = process.env.SW_PORT || new URL(BASE_URL).port || 'default';
  const dir = path.join(os.tmpdir(), `sw-a11y-backdrop-dup-${port}`);
  fs.mkdirSync(dir, { recursive: true });

  const genPath = path.join(dir, 'gen_fixture.go');
  fs.writeFileSync(genPath, GEN_SOURCE);
  try {
    execFileSync('go', ['run', genPath, dir, PERCEPTUAL_ARTIST, EXACT_ARTIST, CLEAN_ARTIST], {
      stdio: 'pipe',
      cwd: dir,
    });
  } catch (err) {
    throw new Error(`seed: generating fanart fixtures failed: ${err.stderr || err.message}`);
  }

  // Assert the fixture has the property the spec depends on BEFORE trusting
  // anything the report says. If the two "near match" files came out
  // byte-identical, the perceptual-only artist would silently become an exact
  // case and the badge assertion would be testing the wrong thing.
  const near1 = fs.readFileSync(path.join(dir, PERCEPTUAL_ARTIST, 'fanart.jpg'));
  const near2 = fs.readFileSync(path.join(dir, PERCEPTUAL_ARTIST, 'fanart2.jpg'));
  if (near1.equals(near2)) {
    throw new Error('seed: the perceptual-only fixture files are byte-identical, so they exercise the EXACT tier instead');
  }
  const dup1 = fs.readFileSync(path.join(dir, EXACT_ARTIST, 'fanart.jpg'));
  const dup2 = fs.readFileSync(path.join(dir, EXACT_ARTIST, 'fanart2.jpg'));
  if (!dup1.equals(dup2)) {
    throw new Error('seed: the exact-duplicate fixture files differ, so no exact redundancy exists');
  }

  await ensureLibrary(request, dir);
  await runScan(request);
  await waitForReport(request);
}
